"""Unit tests for the agent channel journal DB identity contract.

These tests define the expected behavior of the journal DB API before the
implementation exists. They cover command identity, the params digest,
conflicts, and storage read-back. This seed also pins publication-time
supersession: a later activation supersedes the node's previous session, and
publication into the superseded session is rejected as a fence conflict.
Delivery fencing, stale-report rejection, and terminal state transitions
still belong to later units.

DB API contract under test, all on ``dbapi.get_instance()``:

* ``activate_agent_channel(node_uuid, execution_id, workflow_epoch,
  owner_conductor_id, owner_incarnation, token_verifier, profile)``
  returns a session dict with the required keys ``uuid`` and ``fence``.
  Extra keys are allowed.
* ``publish_agent_command(session_uuid, workflow_epoch, invocation_key,
  name, params, reply_boundary, owner_conductor_id, owner_incarnation,
  fence)`` returns a command dict with the required keys ``uuid``,
  ``sequence``, ``session_uuid``, ``workflow_epoch``, ``invocation_key``,
  ``name``, ``params``, ``reply_boundary``, ``params_sha256``, and
  ``state``. Extra keys are allowed. The initial ``state`` is ``queued``.
* ``get_agent_channel_command(command_uuid)`` returns the stored command
  dict for the given UUID.

Identity rules under test:

* The command UUID is stable per (session, workflow_epoch,
  invocation_key). A repeat with the same frozen params returns the same
  UUID and sequence and creates no new row.
* ``params`` is a JSON object with string keys and JSON values. The stored
  digest ``params_sha256`` is the SHA256 hex digest of
  ``json.dumps(params, sort_keys=True, separators=(',', ':'),
  allow_nan=False)`` encoded as UTF-8.
* A changed ``params``, ``name``, or ``reply_boundary`` for the same
  invocation key raises ``exception.AgentChannelCommandConflict``. The
  exception message must not contain param values.
* Invalid params (NaN, non-string keys, or non-JSON values) raise
  ``exception.InvalidParameterValue`` before any row or sequence change.
* An unknown node or session raises an ``exception.NotFound`` error.
* Rows live in ``models.AgentChannelCommand`` with a ``session_uuid``
  column (``session_id`` is accepted as a fallback).

The command UUID is generated by the journal on the first publish. The
caller never passes a command UUID.
"""

import hashlib
import json

import sqlalchemy
from oslo_db.sqlalchemy import enginefacade
from oslo_utils import uuidutils

from ironic.common import exception
from ironic.db.sqlalchemy import models
from ironic.tests.unit.db import base
from ironic.tests.unit.db import utils as db_utils

TOKEN_VERIFIER = 'deadbeef' * 8
OWNER_INCARNATION = 'incarnation-1'
PROFILE = 'agent-poll'
EPOCH = 1
NAME = 'power_on'
BOUNDARY = 'completion'
COMMAND_KEYS = ('uuid', 'sequence', 'session_uuid', 'workflow_epoch',
                'invocation_key', 'name', 'params', 'reply_boundary',
                'params_sha256', 'state')


class AgentChannelJournalTestCase(base.DbTestCase):

    def setUp(self):
        super(AgentChannelJournalTestCase, self).setUp()
        self.node = db_utils.create_test_node()
        self.conductor = db_utils.create_test_conductor()
        self.fence = None

    def _require_method(self, name):
        method = getattr(self.dbapi, name, None)
        self.assertTrue(
            callable(method),
            'dbapi.%s is missing or not callable; the agent channel '
            'journal API is not implemented yet' % name)
        return method

    def _require_conflict_cls(self):
        cls = getattr(exception, 'AgentChannelCommandConflict', None)
        self.assertIsNotNone(
            cls,
            'exception.AgentChannelCommandConflict is not defined yet')
        return cls

    def _require_fence_conflict_cls(self):
        cls = getattr(exception, 'AgentChannelFenceConflict', None)
        self.assertIsNotNone(
            cls,
            'exception.AgentChannelFenceConflict is not defined yet; the '
            'agent channel session fence API is not implemented yet')
        return cls

    def _activate(self, node_uuid, execution_id):
        activate = self._require_method('activate_agent_channel')
        return activate(node_uuid, execution_id, EPOCH, self.conductor.id,
                        OWNER_INCARNATION, TOKEN_VERIFIER, PROFILE)

    def _new_session(self, execution_id=None):
        execution_id = execution_id or uuidutils.generate_uuid()
        self.session = self._activate(self.node.uuid, execution_id)
        self.session_uuid = self.session['uuid']
        self.fence = self.session['fence']
        return self.session

    def _publish(self, session_uuid, invocation_key, name=NAME,
                 params=None, boundary=BOUNDARY, fence=None):
        publish = self._require_method('publish_agent_command')
        if fence is None:
            fence = self.fence
        return publish(session_uuid, EPOCH, invocation_key, name,
                        {} if params is None else params, boundary,
                        self.conductor.id, OWNER_INCARNATION, fence)

    def _get_command(self, command_uuid):
        get = self._require_method('get_agent_channel_command')
        return get(command_uuid)

    def _expected_params_sha(self, params):
        canonical = json.dumps(params, sort_keys=True,
                               separators=(',', ':'), allow_nan=False)
        return hashlib.sha256(canonical.encode('utf-8')).hexdigest()

    def _command_count(self, session_uuid):
        model = getattr(models, 'AgentChannelCommand', None)
        self.assertIsNotNone(
            model,
            'models.AgentChannelCommand is missing; the journal command '
            'table is not implemented yet')
        column = getattr(model, 'session_uuid', None)
        if column is None:
            column = getattr(model, 'session_id', None)
        self.assertIsNotNone(
            column,
            'AgentChannelCommand has neither a session_uuid nor a '
            'session_id column')
        engine = enginefacade.writer.get_engine()
        with engine.connect() as conn:
            stmt = sqlalchemy.select(model).where(column == session_uuid)
            return len(conn.execute(stmt).scalars().all())

    def test_same_invocation_same_params_returns_same_command(self):
        self._new_session()
        params = {'mode': 'iscsi'}
        first = self._publish(self.session_uuid, 'step-1', params=params)
        second = self._publish(self.session_uuid, 'step-1', params=params)
        for key in COMMAND_KEYS:
            self.assertIn(key, first, 'publish result lacks key %s' % key)
        self.assertEqual(first['uuid'], second['uuid'])
        self.assertEqual(first['sequence'], second['sequence'])
        self.assertEqual(first['params_sha256'],
                         self._expected_params_sha(params))
        self.assertEqual(first['state'], 'queued')
        self.assertEqual(self._command_count(self.session_uuid), 1)

    def test_semantically_identical_params_share_digest(self):
        self._new_session()
        ordered = {'b': 2, 'a': {'y': 1, 'x': 2}}
        reordered = {'a': {'x': 2, 'y': 1}, 'b': 2}
        first = self._publish(self.session_uuid, 'step-1', params=ordered)
        second = self._publish(self.session_uuid, 'step-1',
                              params=reordered)
        self.assertEqual(first['uuid'], second['uuid'])
        self.assertEqual(first['params_sha256'], second['params_sha256'])
        self.assertEqual(first['params_sha256'],
                         self._expected_params_sha(ordered))
        self.assertEqual(self._command_count(self.session_uuid), 1)

    def test_changed_params_conflict_keeps_stored_command(self):
        self._new_session()
        secret = 'secret-params-value-123'
        first = self._publish(self.session_uuid, 'step-1',
                              params={'token': 'original'})
        with self.assertRaises(self._require_conflict_cls()) as ctx:
            self._publish(self.session_uuid, 'step-1',
                           params={'token': secret})
        self.assertNotIn(secret, str(ctx.exception))
        stored = self._get_command(first['uuid'])
        self.assertEqual(stored['params'], {'token': 'original'})
        self.assertEqual(self._command_count(self.session_uuid), 1)

    def test_changed_name_conflicts(self):
        self._new_session()
        self._publish(self.session_uuid, 'step-1')
        with self.assertRaises(self._require_conflict_cls()):
            self._publish(self.session_uuid, 'step-1', name='reboot')
        self.assertEqual(self._command_count(self.session_uuid), 1)

    def test_changed_boundary_conflicts(self):
        self._new_session()
        self._publish(self.session_uuid, 'step-1')
        with self.assertRaises(self._require_conflict_cls()):
            self._publish(self.session_uuid, 'step-1',
                          boundary='acceptance')
        self.assertEqual(self._command_count(self.session_uuid), 1)

    def test_different_invocation_key_gets_next_sequence(self):
        self._new_session()
        first = self._publish(self.session_uuid, 'step-1')
        second = self._publish(self.session_uuid, 'step-2')
        self.assertNotEqual(first['uuid'], second['uuid'])
        self.assertEqual(second['sequence'], first['sequence'] + 1)
        self.assertEqual(self._command_count(self.session_uuid), 2)

    def test_input_mutation_after_publish_is_not_stored(self):
        self._new_session()
        params = {'boot': {'device': 'disk', 'order': ['disk', 'net']}}
        stored = {'boot': {'device': 'disk', 'order': ['disk', 'net']}}
        result = self._publish(self.session_uuid, 'step-1', params=params)
        params['boot']['device'] = 'pwned'
        params['boot']['order'].append('floppy')
        command = self._get_command(result['uuid'])
        self.assertEqual(command['params'], stored)
        self.assertEqual(command['params_sha256'],
                         self._expected_params_sha(stored))

    def test_independent_execution_sessions_do_not_reuse_commands(self):
        first_session = self._activate(self.node.uuid,
                                       uuidutils.generate_uuid())
        first_command = self._publish(first_session['uuid'], 'step-1',
                                      fence=first_session['fence'])
        second_session = self._activate(self.node.uuid,
                                        uuidutils.generate_uuid())
        self.assertNotEqual(first_session['uuid'],
                            second_session['uuid'])
        with self.assertRaises(self._require_fence_conflict_cls()):
            self._publish(first_session['uuid'], 'step-1',
                          fence=first_session['fence'])
        second_command = self._publish(second_session['uuid'], 'step-1',
                                       fence=second_session['fence'])
        self.assertNotEqual(first_command['uuid'], second_command['uuid'])
        self.assertEqual(self._command_count(first_session['uuid']), 1)
        self.assertEqual(self._command_count(second_session['uuid']), 1)

    def test_command_is_persisted_and_readable_by_uuid(self):
        self._new_session()
        params = {'mode': 'iscsi', 'target': {'ip': '192.0.2.1'}}
        result = self._publish(self.session_uuid, 'step-1', params=params)
        self.assertEqual(result['workflow_epoch'], EPOCH)
        self.assertEqual(result['state'], 'queued')
        command = self._get_command(result['uuid'])
        for key in COMMAND_KEYS:
            self.assertEqual(command[key], result[key],
                           'command field %s did not survive storage'
                           % key)

    def test_invalid_params_raise_before_any_row(self):
        self._new_session()
        bad_bodies = [{'nan': float('nan')},
                      {1: 'int-key'},
                      {'value': object()}]
        for body in bad_bodies:
            with self.assertRaises(exception.InvalidParameterValue):
                self._publish(self.session_uuid, 'step-1',
                              params=dict(body))
        self.assertEqual(self._command_count(self.session_uuid), 0)

    def test_unknown_node_and_session_raise_not_found(self):
        unknown_node = uuidutils.generate_uuid()
        self.assertRaises(
            exception.NotFound, self._activate, unknown_node,
            uuidutils.generate_uuid())
        unknown_session = uuidutils.generate_uuid()
        self.assertRaises(
            exception.NotFound, self._publish, unknown_session, 'step-1',
            fence=42)
        self.assertEqual(self._command_count(unknown_session), 0)
